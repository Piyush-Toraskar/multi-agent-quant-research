from app.storage import load_blob


def pct(value):
    return 'N/A' if value is None else f'{value * 100:.2f}%'


def number(value):
    return 'N/A' if value is None else f'{value:.3f}'


def make_report(state, settings):
    request = state['request']; data = state['data']; result = state['backtest']
    metrics = result['metrics']; check = state['verification']; risk = state['risk']
    artifact = load_blob(settings.data_dir / 'artifacts', result['artifact_id'])
    lines = ['# Quant Research Report', '',
        '> RESEARCH / EDUCATIONAL USE ONLY. No orders are placed. This report is not personalised investment advice.', '',
        '## Run context', '', f"Question: {request['query']}", '',
        f"Agent mode: **{settings.agent_mode}**. Workflow: **{state['engine']}**. Tool transport: **{settings.tool_transport}**.",
        f"Data source: **{data['metadata']['source']}**.", '',
        f"Symbols: {', '.join(request['symbols'])}; benchmark: {request['benchmark']}.",
        f"Requested dates: {request['start']} inclusive to {request['end']} exclusive.",
        f"Observed data: {data['first_date']} to {data['last_date']}; {data['metadata']['rows']} common observations.",
        f"Snapshot SHA-256: `{data['dataset_id']}`.", f"Backtest artifact SHA-256: `{result['artifact_id']}`.", '',
        '## Hypothesis and method', '', state['plan']['hypothesis'], '', state['plan']['rationale'], '',
        f"Strategy: `{state['plan']['strategy']}`. Lookback: {request['lookback']}; SMA windows: {request['fast_window']}/{request['slow_window']}; rebalance: {request['rebalance']}.",
        f"Commission: {request['commission_bps']} bps; slippage: {request['slippage_bps']} bps per traded notional.",
        f"Execution delay: {artifact['execution_delay']} closing interval(s). Warm-up: {artifact['warmup_observations']} observations.",
        f"Evaluation: {artifact['evaluation_start']} to {artifact['evaluation_end']}; holdout starts {artifact['holdout_start']}.", '',
        '## Measured performance [backtest artifact]', '',
        '| Metric | Strategy | Benchmark | Strategy holdout |', '|---|---:|---:|---:|']
    for label, key, formatter in [('Total return','total_return',pct), ('CAGR','cagr',pct),
        ('Annualised volatility','annualised_volatility',pct), ('Sharpe','sharpe',number),
        ('Sortino','sortino',number), ('Maximum drawdown','max_drawdown',pct)]:
        lines.append(f"| {label} | {formatter(metrics['strategy'][key])} | {formatter(metrics['benchmark'][key])} | {formatter(metrics['holdout'][key])} |")
    lines += ['', f"Executed asset-side trades: {result['trade_count']}. Total trading cost: {result['total_cost']:.2f} in the portfolio's currency units.",
        f"One-way absolute risky-notional turnover: {pct(result['total_turnover'])} over the full run (not annualised).", '',
        '## Risk [risk tool + backtest artifact]', '',
        f"Historical one-day 95% VaR loss: {pct(risk['historical_var_95'])}; CVaR loss: {pct(risk['historical_cvar_95'])}.",
        f"Beta to benchmark: {number(risk['beta_to_benchmark'])}; average risky exposure: {pct(risk['average_exposure'])}.",
        f"Illustrative final-position loss for a simultaneous 20% risky-asset shock: {pct(risk['stress_scenario']['portfolio_loss'])}.", '',
        '## Critic verdict', '', '**' + ('PASSED ENGINEERING CHECKS' if check['passed'] else 'REJECTED') + '**', '']
    for item in check['checks']:
        lines.append(f"- {'PASS' if item['passed'] else 'FAIL'}: {item['name']} - {item['detail']}")
    lines += ['', check['caveat'], '', '## Assumptions and limitations', '']
    lines += ['- ' + x for x in artifact['assumptions'] + data['metadata']['warnings']]
    lines += ['', '## Interpretation', '',
        'These are descriptive results for a fixed research experiment. A positive return or Sharpe ratio does not establish '
        'statistical significance or a persistent trading edge. No hyperparameter search or hypothesis-significance test was performed. '
        'Repeatedly inspecting the holdout makes it unsuitable as an untouched final test. Small samples, selection bias and data revisions remain relevant.', '',
        '## Provenance', '', 'Every number above is generated by deterministic Python tools and saved in the named artifact. '
        'The agent action log records tools and validated arguments, not private model reasoning. Data-source notes, '
        'a replay snapshot and the full daily equity/trade series are retained with this run.']
    if settings.agent_mode == 'demo':
        lines += ['', 'DEMO MODE uses deterministic role policies, not LLM inference. Synthetic market data is not evidence of real strategy performance.']
    return '\n'.join(lines) + '\n'
